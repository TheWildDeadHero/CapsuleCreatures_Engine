"""!Sample connector (D-10 section 7, tools/connectors.py): moods on a game's opponents, maps and cells.

  - party: "ext": {"sample.party_moods": {"mood": "angry", "bonus": 5, "rival": "Scholar Wen"}}
  - map:   "ext": {"sample.party_moods": {"music_mood": "cheerful"}}
  - cell:  "cell_ext": {"sample.party_moods": [{"at": [3, 4], "mood": "calm"}]}

validate warns about a calm opponent with a bonus and refuses an opponent who is its own rival. emit writes
party_moods.h (the types and lookups) and party_moods.cpp (the tables); the game includes the header as
"ext/sample.party_moods/party_moods.h" (its generated folder is on the include path). Pure Python, standard library
only, like every connector.
"""
from __future__ import annotations

from typing import Any

## The moods, in the order the enum numbers them.
MOODS = ("calm", "angry", "cheerful")
## The largest mood bonus.
BONUS_MAX = 20
## The C++ namespace of the outputs.
NAMESPACE = "sample::party_moods"
## A party without a rival.
NO_RIVAL = -1


def register(c: Any) -> None:
   """!Declares the blocks and the hooks.
   @param c  the connector declaration (tools/connectors.py ConnectorSpec)
   @return None
   """
   c.attach("party", c.block(
      mood=c.choice(*MOODS, default="calm", title="Mood", help="How the opponent behaves"),
      bonus=c.integer(0, BONUS_MAX, default=0, title="Mood bonus", help="Added to the AI's scores when not calm"),
      rival=c.ref("party", default=None, title="Rival", help="Another opponent's party")))
   c.attach("map", c.block(music_mood=c.choice(*MOODS, default="calm", title="Music mood")))
   c.attach("cell", c.block(mood=c.choice(*MOODS, title="Mood")))
   c.on_validate(validate)
   c.on_emit(emit)


def validate(record: Any, ctx: Any) -> None:
   """!A calm opponent's bonus does nothing (a warning); an opponent cannot be its own rival (an error).
   @param record  a record carrying the block
   @param ctx     the build context
   @return None
   """
   if record.attach != "party":
      return
   if record.values["mood"] == MOODS.index("calm") and record.values["bonus"]:
      ctx.warning(record, "a calm opponent's mood bonus does nothing")
   if record.values["rival"] is not None and record.values["rival"] == record.number:
      ctx.error(record, "an opponent cannot be its own rival")


def emit(ctx: Any) -> None:
   """!Writes the header and the tables.
   @param ctx  the build context
   @return None
   """
   enum = ", ".join(f"k{m.capitalize()}" for m in MOODS)
   header = [
      "// Generated by the sample.party_moods connector. Do not edit.",
      "#pragma once",
      "#include <cstdint>",
      "",
      f"namespace {NAMESPACE}",
      "{",
      f"enum class Mood : std::uint8_t {{ {enum} }};",
      "struct PartyMood",
      "{",
      "   std::uint16_t party;",
      "   Mood mood;",
      "   std::uint8_t bonus;",
      "   std::int16_t rival;",
      "};",
      "struct CellMood",
      "{",
      "   std::uint16_t map;",
      "   std::int16_t x;",
      "   std::int16_t y;",
      "   Mood mood;",
      "};",
      "const PartyMood* find_party(std::uint16_t party);",
      "Mood map_music(std::uint16_t map);",
      "const CellMood* find_cell(std::uint16_t map, std::int16_t x, std::int16_t y);",
      "}",
      ""]
   ctx.write("party_moods.h", "\n".join(header))
   parties = [f"   {{{r.number}, Mood({r.values['mood']}), {r.values['bonus']}, "
              f"{r.values['rival'] if r.values['rival'] is not None else NO_RIVAL}}},"
              for r in ctx.records("party")]
   maps = {r.number: r.values["music_mood"] for r in ctx.records("map")}
   cells = []
   for r in ctx.records("cell"):
      at = r.name.split("@", 1)[1]
      x, y = (int(v) for v in at.split(","))
      cells.append(f"   {{{ctx.resolve('map', r.name.split('@', 1)[0])}, {x}, {y}, Mood({r.values['mood']})}},")
   body = [
      "// Generated by the sample.party_moods connector. Do not edit.",
      '#include "ext/sample.party_moods/party_moods.h"',
      "",
      f"namespace {NAMESPACE}",
      "{",
      "namespace",
      "{",
      f"const PartyMood kParties[] = {{{'' if parties else ' {0xFFFF, Mood::kCalm, 0, -1} '}",
      *parties,
      "};",
      f"constexpr std::uint16_t kPartyCount = {len(parties)};",
      f"const CellMood kCells[] = {{{'' if cells else ' {0xFFFF, 0, 0, Mood::kCalm} '}",
      *cells,
      "};",
      f"constexpr std::uint16_t kCellCount = {len(cells)};",
      "}",
      "",
      "const PartyMood* find_party(std::uint16_t party)",
      "{",
      "   for (std::uint16_t i = 0; i < kPartyCount; ++i)",
      "   {",
      "      if (kParties[i].party == party)",
      "      {",
      "         return &kParties[i];",
      "      }",
      "   }",
      "   return nullptr;",
      "}",
      "",
      "Mood map_music(std::uint16_t map)",
      "{",
      "   switch (map)",
      "   {",
      *[f"   case {n}: return Mood({mood});" for n, mood in sorted(maps.items())],
      "   default: return Mood::kCalm;",
      "   }",
      "}",
      "",
      "const CellMood* find_cell(std::uint16_t map, std::int16_t x, std::int16_t y)",
      "{",
      "   for (std::uint16_t i = 0; i < kCellCount; ++i)",
      "   {",
      "      if (kCells[i].map == map && kCells[i].x == x && kCells[i].y == y)",
      "      {",
      "         return &kCells[i];",
      "      }",
      "   }",
      "   return nullptr;",
      "}",
      "}",
      ""]
   ctx.write("party_moods.cpp", "\n".join(body))
