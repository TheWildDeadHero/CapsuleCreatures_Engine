def stage_formula_dispatch(stages: Sequence[Mapping[str, Any]]) -> list[str]:
   """!C++ definition of capsule::rules::stage_formula(): a formula stage's id -> its named formula (value, stage).
   @param stages  compiled stages
   @return list of lines
   """
   formulas = sorted({(st["formula_id"], st["formula"]) for st in stages if st["formula"] is not None})
   L = ["int32_t stage_formula(int32_t formula, int32_t v, int32_t stage) {"]
   if not formulas:
      return L + ["    (void)formula;", "    (void)stage;", "    return v;   // no formula stages", "}"]
   L.append("    switch (formula) {")
   L += [f"    case {fid}: return {rc.FORMULA_FUNCTION_PREFIX}{name}(v, stage);" for fid, name in formulas]
   return L + ["    default: return v;", "    }", "}"]


def emit_teachable(species: Sequence[Mapping[str, Any]], lines: list[str]) -> tuple[str, str]:
   """!The species' teachable moves (BattleData::teach_first / teach_moves; C6), when any species lists them.
   @param species  compiled species (key order)
   @param lines    the anonymous namespace's lines (the arrays are appended)
   @return (teach_first, teach_moves) symbols, or ("nullptr", "nullptr") when no species lists them
   """
   if all(sp.get("teachable") is None for sp in species):
      return "nullptr", "nullptr"
   first = [0]
   moves: list[int] = []
   for sp in species:
      moves += sp.get("teachable") or []
      first.append(len(moves))
   lines.append(f"const uint16_t kTeachFirst[] = {{{', '.join(str(x) for x in first)}}};")
   lines.append(f"const uint16_t kTeachMoves[] = {{{', '.join(str(x) for x in moves) or '0'}}};")
   return "kTeachFirst", "kTeachMoves"


def emit(src_name: str, c: Mapping[str, Any]) -> str:
   """!Generates the C++ source.
   @param src_name  manifest name for the header comment
   @param c         from compile_battle()
   @return text
   """
   head = [f"// Generated by tools/battle_compiler.py from {src_name}. Do not edit.",
           '#include "capsule/battle/data.h"', '#include "capsule/battle/pipeline.h"',
           '#include "capsule/battle/ruleset.h"', '#include "capsule/inventory/data.h"',
           '#include "capsule/growth/data.h"', '#include "capsule/battle/data/field.h"',
           '#include "capsule/combine/data.h"',
           '#include "capsule/script/data.h"',
           '#include "capsule/monster/monster.h"', '#include "capsule/storage/storage.h"', "",
           ""]

   # Presenter sequences (global inline constexpr tables, as sequence_compiler emits them).
   for pr in c["presenters"]:
      for motion in (pr["enter"], pr["exit"]):
         if motion["seq"] is not None:
            head.append(motion["seq"])
   head += ["namespace capsule::battle {", "", "namespace {", "", "using text::Code;"]
   T = []   # text definitions, emitted before the tables that use them
   L = []
   texts = {}

   def text(codes: Sequence[int] | None) -> str:
      """!The symbol of a text, defined once per distinct text ("nullptr" for none)."""
      if codes is None:
         return "nullptr"
      key = tuple(codes)
      if key not in texts:
         texts[key] = f"kT{len(texts)}"
         T.append(f"const Code {texts[key]}[] = {{{', '.join(f'0x{x:02X}' for x in codes)}}};")
      return texts[key]

   # Types and chart.
   tnames = [text(t["name"]) for t in c["types"]]
   L.append("const TypeData kTypes[] = {")
   L += [f"    {{{tn}, {t['color']}, {{0, 0, 0}}}}," for tn, t in zip(tnames, c["types"])]
   L.append("};")
   ch = c["chart"]
   L.append(f"const uint8_t kChart[] = {{{', '.join(str(x) for x in ch['matchups'])}}};")
   # chart tiers: TierData {q8, exp, kind, message, reserved}
   L.append("const TierData kTiers[] = {")
   L += [f"    {{{t['q8']}, {t['exp']}, {t['kind_id']}, {t['message']}, 0}},   // {t['name']}" for t in ch["tiers"]]
   L.append("};")
   L.append(f"static_assert(sizeof(kTiers) / sizeof(kTiers[0]) <= kMaxTiers);")
   # Categories.
   L.append("const CategoryData kCategories[] = {")
   L += [f"    {{{k['offense']}, {k['defense']}, {k['flags']}, 0}}," for k in c["categories"]]
   L.append("};")
   L.append(f"static_assert({len(c['categories'])} <= kMaxCategories, \"more move categories than the engine "
            f"holds\");")
   if c.get("hit_categories") is not None:
      # C5: the category of a damaging move hitting with a type that is not its own (structure hit_category_by_type)
      L.append(f"const uint8_t kHitCategories[] = {{{', '.join(str(x) for x in c['hit_categories'])}}};")
   # Stats (StatInfo) and how many there are (the engine's arrays hold kMaxStats).
   L.append(f"constexpr int kStatCount = {len(c['stats'])};")
   L.append("static_assert(kStatCount <= kMaxStats, \"more stats than this platform's engine holds\");")
   L.append("const StatInfo kStats[] = {")
   L += [f"    {{{text(st['label'])}, {st['stage']}, {st['flags']}, {{0, 0}}}},   // {st['name']}"
         for st in c["stats"]]
   L.append("};")
   # Conditions (their logic, the expanded templates included, is their owner).
   rows = ["    {nullptr, nullptr, nullptr, nullptr, nullptr, nullptr, 0xFFFF, 0, 0},"]
   for s in c["statuses"][1:]:
      t = s["texts"]
      tx = [text(s["name"])] + [text(t[k]) for k in STATUS_TEXTS]
      rows.append(f"    {{{', '.join(tx)}, {s['owner']}, {s['color']}, 0}},")
   L.append("const StatusData kStatuses[] = {")
   L += rows
   L.append("};")
   L.append("const WeatherData kWeathers[] = {")
   for w in c["weathers"]:
      t = w["texts"]
      tx = [text(w["name"])] + [text(t[k]) for k in WEATHER_TEXTS]
      L.append(f"    {{{', '.join(tx)}, {w['owner']}, 0}},")
   if not c["weathers"]:
      L.append("    {nullptr, nullptr, nullptr, nullptr, nullptr, 0xFFFF, 0},")
   L.append("};")
   L.append("const VolatileData kVolatiles[] = {")
   L += [f"    {{{text(v['name'])}, {v['owner']}, {v['counter']}, {v['word']}, {v['flags']}, {v['source']}, "
         f"{{0, 0}}}},   // {v['source_name']}" for v in c["volatiles"]]
   if not c["volatiles"]:
      L.append("    {nullptr, 0xFFFF, kNoSlot, kNoSlot, 0, kNoSlot, {0, 0}},")
   L.append("};")
   L.append("const SideCondData kSideConds[] = {")
   L += [f"    {{{text(sc['name'])}, {sc['owner']}, {sc['layers']}, 0}},   // {sc['source_name']}"
         for sc in c["side_conditions"]]
   if not c["side_conditions"]:
      L.append("    {nullptr, 0xFFFF, 1, 0},")
   L.append("};")
   L.append("const FieldCondData kFieldConds[] = {")
   L += [f"    {{{text(fc['name'])}, {fc['owner']}, 0}},   // {fc['source_name']}" for fc in c["field_conditions"]]
   if not c["field_conditions"]:
      L.append("    {nullptr, 0xFFFF, 0},")
   L.append("};")
   # Modifier points (the ruleset's, in id order).
   sources = rc.POINT_SOURCES
   L.append("const PointData kPoints[] = {")
   for name, p in c["pipelines"]["points"].items():
      src = ", ".join(f"PointSource::{rc.camel(s.replace('.', '_'))}" for s in p["sources"])
      L.append(f"    {{{p['range'][0]}, {p['range'][1]}, {{{src}}}, {len(p['sources'])}, {{0, 0, 0}}}},   // {name}")
   if not c["pipelines"]["points"]:
      L.append("    {0, 0, {}, 0, {0, 0, 0}},")
   L.append("};")
   L.append(f"static_assert(static_cast<int>(PointSource::NUM_SOURCES) == {len(sources)}, "
            "\"point sources differ from ruleset_compiler.POINT_SOURCES\");")
   # Effect logic (effect_compiler bank: every move, passive, item, status and weather is an owner).
   L += effect_tables(c["effects"]["bank"])
   # Owner texts.
   L.append(f"const Code* const kTexts[] = {{{', '.join(text(x) for x in c['texts']) or 'nullptr'}}};")
   # Resources (D-25): ResourceData {label, regen, scope, empty, slot, stat, role, raises, max_formula,
   # regen_formula, reserved}; formula ids index rules::resource_formula().
   fid = {name: k for k, name in enumerate(c["resource_formulas"])}

   def formula_id(name: str | None) -> int:
      """!A resource formula's id, or kNone8 (255) for none."""
      return NONE8 if name is None else fid[name]
   L.append("const ResourceData kResources[] = {")
   for r in c["resources"]:
      L.append(f"    {{{text(r['label'])}, {r['regen']}, {r['scope']}, {r['empty']}, {r['slot']}, {r['stat']}, "
               f"0x{r['persist']:02X}, 0x{r['raises']:02X}, {formula_id(r['max'])}, "
               f"{formula_id(r['regen_formula'])}, {{0, 0}}}},   // {r['name']}")
   if not c["resources"]:
      L.append("    {nullptr, 0, 0, 0, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, {0, 0}},")
   L.append("};")
   n_battler = sum(1 for r in c["resources"] if r["scope_name"] == "battler")
   n_move = len(c["resources"]) - n_battler
   L.append(f"static_assert({n_battler} <= kMaxBattlerResources && {n_move} <= kMaxMoveResources, "
            "\"more resources than this platform's engine holds\");")
   L.append(f"static_assert({len(c['resources'])} <= kMaxResources && {max(n_battler - 1, 0)} <= kMaxPools);")
   # Move costs (MoveCost {amount, resource, formula}), each move's in resource order; then the moves (MoveData:
   # ..., cost_first, cost_count, base per move resource).
   costs: list[str] = []
   firsts = []
   for m in c["moves"]:
      firsts.append(len(costs))
      costs += [f"{{{k['amount']}, {k['resource']}, {formula_id(k['formula'])}}}" for k in m["cost"]]
   L.append(f"const MoveCost kMoveCosts[] = {{{', '.join(costs) or '{0, 0xFF, 0xFF}'}}};")
   L.append("const MoveData kMoves[] = {")
   for m, first in zip(c["moves"], firsts):
      base = ", ".join(str(x) for x in m["base"]) or "0"
      L.append(f"    {{{text(m['name'])}, {m['owner']}, {m['fixed_amount']}, {m['fixed_fraction']}, {m['flags']}, "
               f"{first}, {m['power']}, {m['type']}, {m['category']}, {m['accuracy']}, "
               f"{m['priority']}, static_cast<Target>({m['target']}), {m['crit_stage']}, "
               f"{m['statuses']}, {m['fixed_levels']}, {1 if m['formula'] else 0}, {len(m['cost'])}, {{{base}}}}},")
   if not c["moves"]:
      L.append("    {nullptr, 0xFFFF, 0, 0, 0, 0, 0, 0, 0, 0, 0, Target::Self, 0, 0, 0, 0, 0, {0}},")
   L.append("};")
   # Passives, items (their logic is their owner).
   L.append("const HolderData kPassives[] = {")
   L += [f"    {{{text(a['name'])}, {a['owner']}, 0}}," for a in c["passives"]]
   if not c["passives"]:
      L.append("    {nullptr, 0xFFFF, 0},")
   L.append("};")
   L.append("const HolderData kItems[] = {")
   L.append("    {nullptr, 0xFFFF, 0},")
   L += [f"    {{{text(a['name'])}, {a['owner']}, 0}}," for a in c["items"][1:]]
   L.append("};")
   # Traits.
   L.append("const TraitData kTraits[] = {")
   L += [f"    {{{text(nd['name'])}, {{{', '.join(str(x) for x in nd['pct'])}}}, {{0, 0, 0}}}}," for nd in c["traits"]]
   if not c["traits"]:
      L.append("    {nullptr, {}, {0, 0, 0}},")
   L.append("};")
   # Growth.
   for gi, g in enumerate(c["growth"]):
      L.append(f"const uint32_t kGrowth{gi}[] = {{{', '.join(str(x) for x in g)}}};")
   L.append(f"const uint32_t* const kGrowth[] = {{{', '.join(f'kGrowth{i}' for i in range(len(c['growth'])))}}};")
   # Species.
   for si, sp in enumerate(c["species"]):
      L.append(f"const LearnEntry kLearn{si}[] = {{"
               + ", ".join(f"{{{lv}, 0, {mv}}}" for lv, mv in sp["learnset"]) + "};")
   L.append("const SpeciesData kSpecies[] = {")
   for si, sp in enumerate(c["species"]):
      L.append(f"    {{{text(sp['text'])}, kLearn{si}, AssetKey{{0x{sp['key']:08X}u}}, "
               f"AssetKey{{0x{sp['front']:08X}u}}, AssetKey{{0x{sp['back']:08X}u}}, "
               f"{{{', '.join(str(x) for x in sp['base'])}}}, {{{', '.join(str(x) for x in sp['types'])}}}, "
               f"{{{', '.join(str(x) for x in sp['passives'])}}}, {sp['growth']}, {sp['exp_yield']}, "
               f"{len(sp['learnset'])}, 0}},   // {sp['name']}")
   if not c["species"]:
      L.append("    {nullptr, nullptr, AssetKey{0}, AssetKey{0}, AssetKey{0}, {1}, {0, 0xFF, 0xFF}, "
               "{0xFF, 0xFF, 0xFF}, 0, 0, 0, 0},")
   L.append("};")
   # Formats.
   L.append("const FormatData kFormats[] = {")
   for f in c["formats"]:
      def arr(v: Iterable[int]) -> str:
         """!A C++ brace list."""
         return "{" + ", ".join(str(x) for x in v) + "}"
      L.append(f"    {{{text(f['name'])}, {f['positions']}, {f['sides']}, {arr(f['side_of'])}, {arr(f['reach'])}, "
               f"{arr(f['x'])}, {arr(f['y'])}, {arr(f['stand_x'])}, {arr(f['stand_y'])}, {f['party_max']}, "
               f"static_cast<OnTargetFainted>({f['otf']})}},")
   L.append("};")
   # Presenters.
   def motion(m: Mapping[str, Any]) -> str:
      """!A PresenterMotion initializer."""
      return f"{{static_cast<Motion>({m['style']}), {m['frames']}, static_cast<Edge>({m['from']}), 0}}"

   def seq_ref(m: Mapping[str, Any]) -> str:
      """!The address of a motion's sequence, or nullptr."""
      return f"&::{m['symbol']}" if m["symbol"] is not None else "nullptr"
   L.append("const PresenterData kPresenters[] = {")
   for pr in c["presenters"]:
      tx = ", ".join(text(pr["texts"][k]) for k in ("intro", "defeat", "victory"))
      L.append(f"    {{{tx}, {seq_ref(pr['enter'])}, {seq_ref(pr['exit'])}, AssetKey{{0x{pr['sprite']:08X}u}}, "
               f"{motion(pr['enter'])}, {motion(pr['exit'])}, {pr['dx']}, {pr['dy']}, {pr['flags']}, 0}},"
               f"   // {pr['name']}")
   if not c["presenters"]:
      L.append("    {nullptr, nullptr, nullptr, nullptr, nullptr, AssetKey{0}, {}, {}, 0, 0, 0, 0},")
   L.append("};")
   # Parties.
   for ti, t in enumerate(c["parties"]):
      if not t["members"]:
         continue
      L.append(f"const MemberData kMembers{ti}[] = {{")
      for pm in t["members"]:
         L.append(f"    {{{pm['species']}, {pm['item']}, {{{', '.join(str(x) for x in pm['moves'])}}}, "
                  f"{pm['level']}, {pm['passive']}, {pm['genes']}, {pm['trait']}}},")
      L.append("};")
   L.append("const PartyData kParties[] = {")
   for ti, t in enumerate(c["parties"]):
      members = f"kMembers{ti}" if t["members"] else "nullptr"
      L.append(f"    {{{text(t['name'])}, {members}, {t['reward']}, {len(t['members'])}, {t['ai_profile']}, "
               f"{{{', '.join(str(x) for x in t['presenters'])}}}, {t['rank']}, {t['flags']}, "
               f"{{{', '.join(str(x) for x in t['items'])}}}}},")
   if not c["parties"]:
      L.append("    {nullptr, nullptr, 0, 0, 0, {0xFF, 0xFF}, 0, 0, {0, 0, 0, 0}},")
   L.append("};")
   L.append(f"static_assert(kMaxPartyItems == {MAX_PARTY_ITEMS}, \"party items differ from battlec.content\");")
   # G1: AI profiles (battlec/ai.py) and delayed hits (battlec/delayed.py).
   L += emit_ai(c["ai"])
   L += emit_delayed_hits(c["delayed_hits"])
   teach = emit_teachable(c["species"], L)   # C6: the species' teachable moves
   # Messages.
   L.append(f"const Code* const kMessages[] = {{{', '.join(text(m) for m in c['messages'])}}};")
   # the engine's message ids, then the battle's own (BattleData::message_count; C4)
   L.append(f"static_assert(sizeof(kMessages) / sizeof(kMessages[0]) >= static_cast<int>(Msg::NUM_MSGS));")
   # Stages: StageData {name, table, odds, lo, hi, kind, stat, formula}; equal tables are emitted once.
   tables: dict[tuple[Any, ...], str] = {}

   def table(rows: Sequence[tuple[int, int]] | None, kind: str) -> str:
      """!The symbol of a stage table ("nullptr" for none), defined once per distinct table."""
      if rows is None:
         return "nullptr"
      key = (kind,) + tuple(rows)
      if key not in tables:
         tables[key] = f"kStage{kind.title()}{len(tables)}"
         ty = "Odds" if kind == "odds" else "Ratio"
         L.append(f"const {ty} {tables[key]}[] = {{{', '.join(f'{{{a}, {b}}}' for a, b in rows)}}};")
      return tables[key]
   rows = []
   for st in c["stages"]:
      lo, hi = st["range"]
      rows.append(f"    {{{text(st['label'])}, {table(st['table'], 'ratio')}, {table(st['odds'], 'odds')}, {lo}, "
                  f"{hi}, {st['kind_id']}, {st['stat']}, {st['formula_id']}, {{0, 0, 0}}}},   // {st['name']}")
   L.append("const StageData kStages[] = {")
   L += rows or ["    {nullptr, nullptr, nullptr, 0, 0, 0, 0xFF, 0xFF, {0, 0, 0}},"]
   L.append("};")
   L.append(f"static_assert({len(c['stages'])} <= kMaxStages, \"more stages than this platform's engine holds\");")
   lows = [st["range"][0] for st in c["stages"]] or [0]
   highs = [st["range"][1] for st in c["stages"]] or [0]
   L.append(f"static_assert({min(lows)} >= -kStageLimit && {max(highs)} <= kStageLimit, \"a stage's range lies "
            f"within the engine's\");")
   L.append(f"static_assert({len(c['passive_slots'])} <= kMaxPassiveSlots, \"more passive slots than this "
            f"platform's engine holds\");")
   gen = c["rules"]["progress"]["generation"]
   L += emit_generation(gen)
   L.append(f"static_assert({len(gen)} <= kMaxGeneration);")
   L += ["", "} // namespace", ""]
   r = c["rules"]
   learn, exp = r["progress"]["learn"], r["progress"]["exp"]
   turn = turn_rules(r["turn"])
   turn[-1] += ","
   eb = c["effects"]["bank"]
   pool = next(i for i, st in enumerate(c["stats"]) if st["pool"])
   faint = next((k for k, r in enumerate(c["resources"]) if EMPTY_RULES[r["empty"]] == "faint"), NONE8)
   order = next(i for i, st in enumerate(c["stats"]) if st["order"])
   odds = next((i for i, st in enumerate(c["stats"]) if st.get("odds")), NONE8)
   # C5: the move_type point only when a handler can change a hit's type (else no hit runs it)
   move_type_point = c["pipelines"]["points"][rc.MOVE_TYPE_POINT]["id"] if point_handled(c, rc.MOVE_TYPE_POINT) \
      else NONE8
   L += ["const BattleData kData = {",
         "    kTypes, kChart, kTiers, kStatuses, kWeathers, kVolatiles, kSideConds, kFieldConds, kMoves, kPassives,",
         "    kItems, kSpecies, kGrowth, kTraits, kFormats, kParties, kPresenters, kCategories,",
         f"    {'kHitCategories' if c.get('hit_categories') is not None else 'nullptr'}, kStats, kMessages,",
         "    kStages, kPoints, kTexts, kResources, kMoveCosts,",
         f"    {{kEffectCode, kEffectPrograms, kEffectHandlers, kEffectOwners, {len(eb.code)}, {len(eb.programs)}, "
         f"{len(eb.handlers)}, {len(eb.owners)}, 0}},",
         f"    {{{r['stat_cap']}, {r['fallback_move']}, {r['level_max']}, {r['rank_max']}, {r['self_hit_power']}, "
         f"{r['self_hit_category']}, {move_type_point},",
         *turn,
         f"     {{kGeneration, {len(gen)}, {learn['on_full']}, {learn['default_moves']}, {exp['share']}, "
         f"{exp['receivers']}, {exp['outsider']}}}",
         "    },",
         f"    {len(c['moves'])}, {len(c['species'])}, {len(c['items'])}, {len(c['parties'])}, {len(c['texts'])}, "
         f"{len(c['types'])}, "
         f"{len(c['statuses'])}, {len(c['weathers'])}, {len(c['volatiles'])}, {len(c['side_conditions'])}, "
         f"{len(c['field_conditions'])}, {c['layout']['status_bits']}, {len(c['passives'])}, {len(c['growth'])}, "
         f"{len(c['traits'])}, {len(c['formats'])}, {len(c['presenters'])}, {len(c['categories'])}, kStatCount, "
         f"{pool}, {order}, {len(c['stages'])}, {len(c['pipelines']['points'])},",
         f"    {len(ch['tiers'])}, {ch['combine_id']}, {ch['types_per_species']}, {ch['added_types']}, "
         f"{ch['above']}, {ch['below']}, {stage_of_kind(c['stages'], 'accuracy')}, "
         f"{stage_of_kind(c['stages'], 'evasion')}, {stage_of_kind(c['stages'], 'crit')}, "
         f"{shared_stat_stage(c['stages'])}, {len(c['resources'])}, {faint}, {n_move}, {odds},",
         f"    {len(c['passive_slots'])}, 0x{passive_rolled_mask(c['passive_slots']):02X}, "
         f"0x{(1 << passive_slot_bits(c['passive_slots'])) - 1:02X}, {len(c['messages'])},",
         # G1: AI profiles and delayed hits
         f"    kAiProfiles, kAiRules, kDelayedHits, {len(c['ai']['profiles'])}, {c['ai']['default']}, "
         f"{len(c['delayed_hits'])},",
         # C6: the weather-suppressing tags, the species' teachable moves
         f"    0x{c.get('weather_suppress_tags', 0):04X}, {teach[0]}, {teach[1]},",
         "};", "",
         # G3: the recruit rules (battlec/recruit.py; their own symbol, not a kData field)
         *emit_recruit(c.get("recruit")), "",
         "} // namespace capsule::battle", "", "namespace capsule::monster {", "", "namespace {",
         f"const uint16_t kOffsets[] = {{{', '.join(f'0x{x:04X}' for x in c['layout']['offsets'])}}};",
         "static_assert(sizeof(kOffsets) / sizeof(kOffsets[0]) == static_cast<int>(Role::NUM_ROLES));",
         f"const uint8_t kWidths[] = {{{', '.join(str(x) for x in c['layout']['widths'])}}};",
         "static_assert(sizeof(kWidths) / sizeof(kWidths[0]) == static_cast<int>(Role::NUM_ROLES));",
         f"const uint8_t kCounts[] = {{{', '.join(str(x) for x in c['layout']['counts'])}}};",
         "static_assert(sizeof(kCounts) / sizeof(kCounts[0]) == static_cast<int>(Role::NUM_ROLES));"]
   lay = c["layout"]
   slots = lay["custom"] + lay["unstored"]
   if slots:
      # custom roles (D-22 decision 2): RoleSlot {name hash, initial value, offset, width, count}; the unstored ones
      # (E13a) after the stored ones, without bits (offset kAbsent: computed on read)
      L.append("const RoleSlot kCustom[] = {")
      for cr in slots:
         offset = cr["offset"] if "offset" in cr else f"0x{ROLE_ABSENT:04X}"
         L.append(f"    {{0x{cr['name_hash']:08X}u, {cr['default']}u, {offset}, {cr['width']}, {cr['count']}}},"
                  f"   // {cr['name']} (role 0x{cr['id']:02X}{'' if 'offset' in cr else ', unstored'})")
      L.append("};")
      L.append(f"static_assert(sizeof(kCustom) / sizeof(kCustom[0]) <= kMaxCustomRoles);")
   L += [f"static_assert({lay['bytes']} <= kMaxRecordBytes, \"a larger record than this platform's engine holds\");",
         f"static_assert({lay['party_size']} <= kMaxPartySize, \"a larger party than this platform's engine holds\");",
         f"static_assert({lay['move_slots']} <= kMaxMoveSlots);",
         "} // namespace", "",
         f"const Layout kLayout = {{kOffsets, kWidths, kCounts, {'kCustom' if slots else 'nullptr'}, "
         f"0x{lay['hash']:08X}u, {lay['bytes']}, {lay['stat_count']}, {lay['move_slots']}, {lay['party_size']}, "
         f"{len(lay['custom'])}, {len(lay['unstored'])}, {{0}}, 0x{lay['record_hash']:08X}u}};",
         "", "} // namespace capsule::monster", "", "namespace capsule::rules {", ""]
   formulas = [st["formula"] for st in c["stats"]]
   L += rc.emit_functions(c["ruleset"], formulas)
   L += [""] + rc.emit_stat_dispatch(formulas)
   L += [""] + stage_formula_dispatch(c["stages"])
   L += [""] + formula_dispatch(c["resource_formulas"])
   # E13b: effect logic's species_field(); G3: the recruit rate field
   reads_fields = logic_reads_species_fields(c) or (c.get("recruit") or {}).get("rate_name") is not None
   # G4: growth reads them too (species.NAME in its rules, the training yields)
   reads_fields = reads_fields or ("transform" in c and growth_reads_fields(c["transform"]))
   L += [""] + emit_species_fields(c["species"], c.get("species_fields", []), gen, reads_fields)
   L += emit_derive(gen, c["layout"], c.get("species_fields", []))
   L += rc.emit_pipelines(c["pipelines"])
   # Point handlers: pure effect code (effect_compiler.emit_pure_cpp), one dispatcher.
   L += ["", "namespace effect = capsule::battle::effect;", ""]
   L += ec.emit_pure_cpp(c["point_handlers"], "point_handler").splitlines()
   L += ["", "} // namespace capsule::rules", ""]
   # G2: the bag's pockets, the items' bag and use fields, the shops (battlec/inventory.py)
   L += emit_inventory(c["inventory"])
   # G4: the transformation rules, forms, context values and training (battlec/growth.py)
   L += emit_growth(c)
   # G3: the storage boxes (battlec/storage.py)
   L += emit_storage(c["storage"])
   # F1: the lead rule and the count of the timed field effects (battlec/field.py)
   L += emit_field(c["field"])
   # B1: the combination methods (battlec/combine.py)
   L += emit_combine(c)
   return "\n".join(head + T + L)


def turn_rules(tr: Mapping[str, Any]) -> list[str]:
   """!The TurnRules initializer of a compiled turn structure (battlec/turn.py compile_turn()), every array
   padded to its capacity.
   @param tr  compiled turn
   @return C++ lines
   """
   def padded(values: Sequence[int], size: int) -> str:
      """!A brace list of values padded with 0 to size entries."""
      return "{" + ", ".join(str(v) for v in list(values) + [0] * (size - len(values))) + "}"
   br = tr["brackets"]
   phases = [f"{{{e['phase']}, {e['each']}, {len(e['sources'])}, {padded(e['sources'], len(SOURCES))}}}"
             for e in tr["end"]]
   phases += ["{0, 0, 0, " + padded([], len(SOURCES)) + "}"] * (MAX_END_PHASES - len(tr["end"]))
   return [f"     {{{br['run']}, {br['switch']}, {br['item']}, {br['move']}, {br['move_priority']}, {tr['tie']}, "
           f"{tr['send_order']}, {tr['start_hooks']}, {padded(tr['effect_order'], len(SOURCES))}, {len(tr['end'])}, {{",
           *[f"        {ph}," for ph in phases], "     }}"]


def reads_ref(node: Any, ref: int) -> bool:
   """!Whether a pure point handler's IR reads a ref.
   @param node  IR node (effect_compiler PureExpr / statements: nested tuples and lists)
   @param ref   REFS index
   @return true when some ("get", ref, ...) is in it
   """
   if isinstance(node, (tuple, list)):
      if len(node) > 1 and node[0] == "get" and node[1] == ref:
         return True
      return any(reads_ref(n, ref) for n in node)
   if isinstance(node, dict):
      return any(reads_ref(n, ref) for n in node.values())
   return False


def logic_reads_species_fields(c: Mapping[str, Any]) -> bool:
   """!Whether the battle's effect logic reads a species field (E13b: Ref species_field in a program or a point
   handler; F1: an encounter_field bias), so rules::species_field_of() needs the table.
   @param c  from compile_battle()
   @return true when something reads one
   """
   ref = ec.REFS.index("species_field")
   prefer_field = ec.ENCOUNTER_KINDS.index("encounter_field")
   for _at, name, values in ec.instructions(c["effects"]["bank"].code):
      if name == "Get" and values[0] == ref:
         return True
      if name == "Encounter" and values[0] == prefer_field:
         return True   # F1: an encounter hook's pick by a species field
   return any(reads_ref(e["ir"], ref) for e in c["point_handlers"])


def effect_tables(bank: ec.Bank) -> list[str]:
   """!The effect bank's tables (kEffectCode, kEffectPrograms, kEffectHandlers, kEffectOwners); an empty table gets
   one zero entry the bank's counts leave out.
   @param bank  the compiled bank
   @return lines
   """
   L = [f"const uint8_t kEffectCode[] = {{{', '.join(f'0x{b:02X}' for b in bank.code) or '0'}}};",
        "const effect::ProgramInfo kEffectPrograms[] = {"]
   for (off, length, stack, locs, flags, events), label in zip(bank.programs, bank.labels):
      L.append(f"    {{{off}, {length}, {stack}, {locs}, {flags}, {events}, 0}},   // {label}")
   if not bank.programs:
      L.append("    {0, 0, 0, 0, 0, 0, 0},")
   L += ["};", "const effect::Handler kEffectHandlers[] = {"]
   L += [f"    {{{hook}, {flags}, {prog}}}," for hook, flags, prog in bank.handlers]
   if not bank.handlers:
      L.append("    {0, 0, 0},")
   L += ["};", "const effect::Owner kEffectOwners[] = {"]
   for (hooks, points, ident_, first, tags, count, kind, flags), name in zip(bank.owners, bank.owner_names):
      L.append(f"    {{{ec.hook_mask_cpp(hooks)}, 0x{points:08X}u, {ident_}, {first}, {tags}, {count}, "
               f"static_cast<effect::OwnerKind>({kind}), {flags}, {{0, 0, 0}}}},   // {name}")
   if not bank.owners:
      L.append("    {" + ec.hook_mask_cpp(0) + ", 0, 0, 0, 0, 0, effect::OwnerKind::Move, 0, {0, 0, 0}},")
   L.append("};")
   return L


def emit_ids(src_name: str, c: Mapping[str, Any]) -> str:
   """!Generates the header of constexpr indices.
   @param src_name  manifest name
   @param c         from compile_battle()
   @return text
   """
   L = [f"// Generated by tools/battle_compiler.py from {src_name}. Do not edit.", "#pragma once", "",
        "#include <cstdint>", "", "/// Indices into the build's battle data (capsule::battle::kData).",
        "namespace battle_ids {", ""]
   groups = [("TYPE", "TYPES", "uint8_t", c["names"]["types"], 0),
             ("STATUS", "STATUSES", "uint8_t", c["names"]["statuses"], 1),
             ("WEATHER", "WEATHERS", "uint8_t", c["names"]["weathers"], 0),
             ("VOLATILE", "VOLATILES", "uint8_t", c["names"]["volatiles"], 0),
             ("SIDE_COND", "SIDE_CONDS", "uint8_t", c["names"]["side_conditions"], 0),
             ("FIELD_COND", "FIELD_CONDS", "uint8_t", c["names"]["field_conditions"], 0),
             ("FLAG", "FLAGS", "uint8_t", c["names"]["move_flags"], 0),
             ("TAG", "TAGS", "uint8_t", c["names"]["tags"], 0),
             ("PASSIVE", "PASSIVES", "uint8_t", c["names"]["passives"], 0),
             ("TRAIT", "TRAITS", "uint8_t", c["names"]["traits"], 0),
             ("FORMAT", "FORMATS", "uint8_t", c["names"]["formats"], 0),
             ("CATEGORY", "CATEGORIES", "uint8_t", c["names"]["categories"], 0),
             ("PRESENTER", "PRESENTERS", "uint8_t", c["names"]["presenters"], 0),
             ("STAT", "STATS", "uint8_t", c["names"]["stats"], 0),
             ("RESOURCE", "RESOURCES", "uint8_t", c["names"]["resources"], 0),
             ("STAGE", "STAGES", "uint8_t", [st["name"] for st in c["stages"]], 0),
             ("TIER", "TIERS", "uint8_t", [t["name"] for t in c["chart"]["tiers"]], 0),
             ("POINT", "POINTS", "uint8_t", list(c["pipelines"]["points"]), 0),
             # G1: AI profiles and delayed hits
             ("AI_PROFILE", "AI_PROFILES", "uint8_t", c["ai"]["names"], 0),
             ("DELAYED_HIT", "DELAYED_HITS", "uint8_t", [d["name"] for d in c["delayed_hits"]], 0),
             ("MOVE", "MOVES", "uint16_t", c["names"]["moves"], 0),
             ("ITEM", "ITEMS", "uint16_t", c["names"]["items"], 1),
             ("PARTY", "PARTIES", "uint16_t", c["names"]["parties"], 0),
             ("SPECIES", "SPECIES", "uint16_t", [s["name"] for s in c["species"]], 0)]
   for prefix, plural, ty, names, first in groups:
      seen = set()
      for i, name in enumerate(names):
         idn = f"{prefix}_{ident(name)}"
         if idn in seen:
            raise ManifestError(f"{src_name}: two {prefix.lower()} names give the identifier {idn}")
         seen.add(idn)
         L.append(f"inline constexpr {ty} {idn} = {first + i};")
      L.append(f"inline constexpr int NUM_{plural} = {len(names) + first};")
      L.append("")
   # record roles the layout holds (engine roles by registry ID, custom roles 0x80 + index): role_get / role_set.
   # C5: an unstored custom role (E13a) has no ROLE_ constant (monster::get() / field scripts' role_get read 0 for
   # it): UNSTORED_ROLE_<NAME> names its ID for battle::record_value()
   seen = set()
   unstored = c["layout"].get("unstored_ids", {})
   for name, rid in c["layout"]["ids"].items():
      idn = f"{UNSTORED_ROLE_PREFIX if name in unstored else ROLE_PREFIX}{ident(name)}"
      if idn in seen:
         raise ManifestError(f"{src_name}: two role names give the identifier {idn}")
      seen.add(idn)
      L.append(f"inline constexpr uint8_t {idn} = 0x{rid:02X};")
   L.append(f"inline constexpr int NUM_CUSTOM_ROLES = {len(c['layout']['custom'])};")
   L.append("")
   L += inventory_ids(c["inventory"], src_name)   # G2: POCKET_ / SHOP_
   L += growth_ids(c, src_name)   # G4: TRIGGER_ / CONTEXT_ / FORM_
   L += storage_ids(c["storage"])                 # G3: NUM_BOXES / BOX_SIZE
   L += field_ids(c["field"])                     # F1: FIELD_EFFECT_<NAME>
   L += combine_ids(c)                            # B1: COMBINE_METHOD_<NAME>
   L += nursery_ids(c)                            # B2: NURSERY_SLOTS
   L += ["} // namespace battle_ids", ""]
   return "\n".join(L)


def write_if_changed(path: Path, text: str) -> None:
   """!Writes a file only when its content changes (keeps builds incremental).
   @param path  file
   @param text  content
   @return None
   """
   path.parent.mkdir(parents=True, exist_ok=True)
   if not path.exists() or path.read_bytes() != text.encode("utf-8"):
      path.write_text(text, encoding="utf-8", newline="\n")

