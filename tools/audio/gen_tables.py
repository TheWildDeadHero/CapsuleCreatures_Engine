#!/usr/bin/env python3
"""!Writes the audio core's integer tables (D-34, M4 B1a): src/audio/tables.cpp.

Every table is computed from its formula (format document section 7), never copied:

- lengths: the 49 NOTE / WAIT durations, 0-24 ticks and every multiple of 4 or 6 up to 96 (the musical durations of
  96 ticks per whole note);
- octave: round(2^31 x 2^(i/12)) for the 12 notes (sampled channels: freq(k) = octave[k % 12] >> (14 - k / 12));
- tone octave: round(-131072 / f(36 + i)), f(k) = 440 x 2^((k - 69) / 12) (tone channels: C(k) = value >> (k / 12));
- noise: NR43 values, shift 13 - i / 4 in the high nibble and divisor 7 - i % 4, the last four 3, 2, 1, 0;
- wave volume: NR32 by envelope level (0-1 mute, 2-5 25 %, 6-9 50 %, 10-13 75 %, 14-15 100 %);
- deltas: the DPCM steps i^2 for i < 8, -(16 - i)^2 from 8;
- rate samples: samples per frame of the 12 mixing rates, round(rate x 10000 / 597275).

Exact arithmetic (Decimal at 60 digits) decides each rounding. Usage: gen_tables.py [--check] [OUT]
(default OUT: src/audio/tables.cpp beside this tool's repository); --check exits 1 when OUT differs.
"""
from __future__ import annotations

import argparse
import sys
from decimal import ROUND_HALF_EVEN, Decimal, getcontext
from pathlib import Path

## The repository (this tool is tools/audio/gen_tables.py).
REPO = Path(__file__).resolve().parent.parent.parent
## An octave doubles the frequency.
OCTAVE_RATIO = 2
## Decimal digits for the exact roundings.
PRECISION = 60
## Notes per octave.
NOTES = 12
## The octave table's scale: 2^31.
OCTAVE_SCALE = 2 ** 31
## The tone table's numerator.
TONE_NUMERATOR = -131072
## The tone table's first key.
TONE_FIRST_KEY = 36
## Concert pitch: key 69 at 440 Hz.
CONCERT_KEY = 69
## Concert pitch, Hz.
CONCERT_HZ = 440
## Durations 0..24 come first.
SHORT_LENGTHS = 25
## The longest duration (a whole note).
WHOLE_NOTE = 96
## Longer durations are multiples of these.
LENGTH_STEPS = (4, 6)
## Noise entries.
NOISE_COUNT = 60
## Noise entries with a shift (four per shift).
NOISE_SHIFTED = 56
## Noise: the first entry's shift.
NOISE_TOP_SHIFT = 13
## Noise: divisors per shift.
NOISE_DIVISORS = 4
## Noise: the first divisor.
NOISE_TOP_DIVISOR = 7
## Noise: the last entry's value (they count down to 0).
NOISE_LAST = NOISE_COUNT - 1
## Bits of a nibble.
NIBBLE_BITS = 4
## NR32 values by level band, and the band's first level.
WAVE_BANDS = ((0, 0x00), (2, 0x60), (6, 0x40), (10, 0x80), (14, 0x20))
## Envelope levels of the wave volume table.
WAVE_LEVELS = 16
## DPCM deltas.
DELTA_COUNT = 16
## DPCM: positive deltas below this index.
DELTA_HALF = 8
## The 12 mixing rates, Hz.
RATES = (5734, 7884, 10512, 13379, 15768, 18157, 21024, 26758, 31536, 36314, 40137, 42048)
## The screen's refresh rate, Hz x 10,000.
FRAME_RATE_SCALED = 597275
## Its scale.
FRAME_RATE_DIVISOR = 10000
## Longest output line.
LINE_WIDTH = 116

## The file's head.
HEADER = """/// @file
/// The audio core's integer tables (D-34, M4 B1a), generated by tools/audio/gen_tables.py from their formulas
/// (see that tool). Do not edit: run the tool (a test checks this file against it).
#include "audio_internal.h"

namespace capsule::audio::detail
{
"""
## The file's tail.
FOOTER = """
}   // namespace capsule::audio::detail
"""


def exact_round(x: Decimal) -> int:
   """!Rounds to the nearest integer (no exact halves occur in these tables).
   @param x  the value
   @return the integer
   """
   return int(x.to_integral_value(rounding=ROUND_HALF_EVEN))


def lengths() -> list[int]:
   """!The NOTE / WAIT durations.
   @return 49 tick counts
   """
   longer = [n for n in range(SHORT_LENGTHS, WHOLE_NOTE + 1) if any(n % s == 0 for s in LENGTH_STEPS)]
   return list(range(SHORT_LENGTHS)) + longer


def octave() -> list[int]:
   """!round(2^31 x 2^(i/12)).
   @return 12 values
   """
   two = Decimal(OCTAVE_RATIO)
   return [exact_round(OCTAVE_SCALE * (two.ln() * i / NOTES).exp()) for i in range(NOTES)]


def tone_octave() -> list[int]:
   """!round(-131072 / f(36 + i)).
   @return 12 values
   """
   two = Decimal(OCTAVE_RATIO)
   out = []
   for i in range(NOTES):
      f = CONCERT_HZ * (two.ln() * Decimal(TONE_FIRST_KEY + i - CONCERT_KEY) / NOTES).exp()
      out.append(exact_round(Decimal(TONE_NUMERATOR) / f))
   return out


def noise() -> list[int]:
   """!NR43 values by noise entry.
   @return 60 bytes
   """
   out = []
   for i in range(NOISE_COUNT):
      if i < NOISE_SHIFTED:
         out.append(((NOISE_TOP_SHIFT - i // NOISE_DIVISORS) << NIBBLE_BITS) | (NOISE_TOP_DIVISOR - i % NOISE_DIVISORS))
      else:
         out.append(NOISE_LAST - i)
   return out


def wave_volume() -> list[int]:
   """!NR32 by envelope level.
   @return 16 bytes
   """
   return [[value for first, value in WAVE_BANDS if level >= first][-1] for level in range(WAVE_LEVELS)]


def deltas() -> list[int]:
   """!The DPCM deltas.
   @return 16 signed values
   """
   return [i * i if i < DELTA_HALF else -(DELTA_COUNT - i) * (DELTA_COUNT - i) for i in range(DELTA_COUNT)]


def rate_samples() -> list[int]:
   """!Samples per frame of each mixing rate.
   @return 12 counts
   """
   return [exact_round(Decimal(r) * FRAME_RATE_DIVISOR / FRAME_RATE_SCALED) for r in RATES]


def table(ctype: str, name: str, count: str, values: list[int], doc: str, suffix: str = "") -> str:
   """!One C++ array definition.
   @param ctype   element type
   @param name    the array
   @param count   its size expression
   @param values  its values
   @param doc     its comment
   @param suffix  literal suffix
   @return the source
   """
   lines = [f"\n/// {doc}", f"const {ctype} {name}[{count}] = {{"]
   line = "  "
   for v in values:
      item = f" {v}{suffix},"
      if len(line) + len(item) > LINE_WIDTH:
         lines.append(line)
         line = "  "
      line += item
   lines.append(line)
   lines.append("};")
   return "\n".join(lines) + "\n"


def render() -> str:
   """!The whole tables.cpp.
   @return its text
   """
   getcontext().prec = PRECISION
   parts = [HEADER,
            table("uint8_t", "kLengths", "kLengthCount", lengths(), "Ticks of NOTE i / WAIT i."),
            table("uint32_t", "kOctave", "kNotes", octave(), "round(2^31 x 2^(i/12)).", "u"),
            table("int16_t", "kToneOctave", "kNotes", tone_octave(), "round(-131072 / f(36 + i))."),
            table("uint8_t", "kNoise", "kNoiseCount", noise(), "Noise NR43 values by key - 21."),
            table("uint8_t", "kWaveVolume", "kWaveVolumeCount", wave_volume(),
                  "NR32 by envelope level (the goal is at most 15)."),
            table("int8_t", "kDeltas", "kDeltaCount", deltas(), "DPCM deltas."),
            table("uint16_t", "kRateSamples", "kRateCount", rate_samples(), "Samples per frame by rate index."),
            FOOTER]
   return "".join(parts)


def main(argv: list[str]) -> int:
   """!Command line.
   @param argv  arguments
   @return exit status
   """
   ap = argparse.ArgumentParser(description="Writes src/audio/tables.cpp.")
   ap.add_argument("out", nargs="?", default=str(REPO / "src" / "audio" / "tables.cpp"))
   ap.add_argument("--check", action="store_true", help="exit 1 when the file differs")
   args = ap.parse_args(argv)
   text = render()
   out = Path(args.out)
   if args.check:
      if not out.exists() or out.read_bytes() != text.encode("utf-8"):
         print(f"{out}: out of date (run tools/audio/gen_tables.py)", file=sys.stderr)
         return 1
      return 0
   out.write_text(text, encoding="utf-8", newline="\n")
   return 0


if __name__ == "__main__":
   sys.exit(main(sys.argv[1:]))
