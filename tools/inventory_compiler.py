#!/usr/bin/env python3
"""!D-36 §3.1 G1: a game's inventory without battle data.

   inventory_compiler.py INVENTORY.json OUT.cpp [--ids IDS.h] [--platform P] [--code-page PAGE.json]

A project names a `capsule.inventory/1` file as `"inventory"` in its `capsule.project/1` when its bag is used by its
own code and it has no battle data (a game with battle data gives its pockets in its structure manifest and its items
in battle.json, docs/BATTLE.md). The file holds:

- `schema`: "capsule.inventory/1";
- `pockets`: the pockets and stores, as a structure manifest's (tools/battlec/inventory.py: name, label, capacity,
  quantity_max, sort, stacks, close_up, store);
- `items`: the items in id order (id 1 first): name (its save key is the asset key "item:NAME"), pocket, price,
  holdable, consumed, key; no use (an inventory without battle data has no effect logic);
- `editor` (optional): notes for the studio.

The output defines capsule::inventory::kInventory (battlec.inventory.emit_inventory(), the same text the battle
compiler writes), checked against the platform's limits (pockets, slots); --ids writes the pockets' indices
(POCKET_<NAME>). It replaces the engine's default, src/inventory/inventory_empty.cpp, at link.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import text_encoder  # noqa: E402
from battlec.common import ManifestError, Texts, check_keys, register_keys  # noqa: E402
from battlec.inventory import (DEFAULT_USE, NO_SAVE_KEY, compile_pockets, emit_inventory,  # noqa: E402
                               inventory_ids, item_fields)
from build_settings import SettingsError, platform_limits  # noqa: E402

## The file's schema.
SCHEMA = "capsule.inventory/1"
## Exit status: written.
EXIT_OK = 0
## Exit status: the file is not a valid inventory.
EXIT_ERROR = 1
## The item fields an inventory without battle data takes.
ITEM_KEYS = {"name", "pocket", "price", "holdable", "consumed", "key"}

register_keys({"inventory_file": {"schema", "editor", "pockets", "items"},
               "inventory_item": ITEM_KEYS})


def compile_file(path: Path, platform: str | None = None,
                 codepage: text_encoder.CodePage = text_encoder.DEFAULT) -> dict[str, Any]:
   """!Reads and compiles an inventory file.
   @param path      the capsule.inventory/1 file
   @param platform  the platform whose limits apply (None: build_settings.DEFAULT_PLATFORM, the strictest)
   @param codepage  the game's code page (the pockets' labels)
   @return {"pockets", "items" (item_fields() per id, index 0 None), "shops" (none), "slot_count"}, as the battle
           compiler's compile_inventory()
   @throws ManifestError when the file is not a valid inventory
   """
   where = str(path)
   try:
      data = json.loads(path.read_text(encoding="utf-8"))
   except (OSError, json.JSONDecodeError) as e:
      raise ManifestError(f"{where}: {e}") from e
   check_keys(data, "inventory_file", where)
   if data.get("schema") != SCHEMA:
      raise ManifestError(f"{where}: schema must be {SCHEMA}")
   enc = Texts(codepage)
   pockets = compile_pockets(data.get("pockets"), platform_limits(platform), where, enc)
   entries = data.get("items", [])
   if not isinstance(entries, list):
      raise ManifestError(f"{where}: items must list the items in id order")
   fields: list[dict[str, Any] | None] = [None]
   names: dict[str, int] = {}
   keys: dict[int, str] = {}
   for i, entry in enumerate(entries):
      w = f"{where}: items[{i}]"
      check_keys(entry, "inventory_item", w)
      name = entry.get("name")
      if not isinstance(name, str) or not name:
         raise ManifestError(f"{w}.name: needs a name")
      if name in names:
         raise ManifestError(f"{w}.name: {name!r} given twice")
      names[name] = i + 1
      f = item_fields(entry, pockets, f"{w} ({name})")
      if f["use"] != DEFAULT_USE:
         raise ManifestError(f"{w}: an inventory without battle data has no effect logic (no use)")
      # C7: key 0 is the engine's "no item"; two items with one key would load as one
      if f["save_key"] == NO_SAVE_KEY or keys.setdefault(f["save_key"], name) != name:
         raise ManifestError(f"{w}: {name!r}'s save key 0x{f['save_key']:08X} is 0 or another item's; rename it")
      fields.append(f)
   return {"pockets": pockets, "items": fields, "shops": [], "slot_count": sum(p["capacity"] for p in pockets)}


def emit_cpp(src_name: str, inv: dict[str, Any]) -> str:
   """!The C++ source defining the build's inventory tables.
   @param src_name  the file's name (the header comment)
   @param inv       compile_file()'s result
   @return C++ source
   """
   L = [f"// Generated by tools/inventory_compiler.py from {src_name}. Do not edit.",
        "#include \"capsule/inventory/data.h\"", ""]
   return "\n".join(L + emit_inventory(inv))


def emit_ids(src_name: str, inv: dict[str, Any]) -> str:
   """!The pockets' indices for the game's code.
   @param src_name  the file's name
   @param inv       compile_file()'s result
   @return C++ header
   """
   L = [f"// Generated by tools/inventory_compiler.py from {src_name}. Do not edit.", "#pragma once", "",
        "#include <cstdint>", ""]
   return "\n".join(L + inventory_ids(inv, src_name))


def write_if_changed(path: Path, text: str) -> None:
   """!Writes a file only when its text changes (so the sources that include it rebuild only then).
   @param path  the file
   @param text  its text
   @return None
   """
   if not path.exists() or path.read_text(encoding="utf-8") != text:
      path.parent.mkdir(parents=True, exist_ok=True)
      path.write_text(text, encoding="utf-8")


def main(argv: Sequence[str] | None = None) -> int:
   """!The command line (see the module's comment).
   @param argv  arguments (default: sys.argv[1:])
   @return the exit status
   """
   p = argparse.ArgumentParser(description="a game's inventory without battle data (D-36 §3.1 G1)")
   p.add_argument("inventory", type=Path, help="the capsule.inventory/1 file")
   p.add_argument("out", type=Path, help="the C++ source to write")
   p.add_argument("--ids", type=Path, default=None, help="the pockets' indices header to write")
   p.add_argument("--platform", default=None,
                  help="the platform whose limits apply (default: the GBA's, the strictest)")
   p.add_argument("--code-page", type=Path, default=None, help="the game's code page (the pockets' labels)")
   args = p.parse_args(argv)
   try:
      codepage = text_encoder.load(args.code_page)
      inv = compile_file(args.inventory, args.platform, codepage)
   except (ManifestError, SettingsError, text_encoder.TextError) as e:
      print(f"inventory_compiler: {e}", file=sys.stderr)
      return EXIT_ERROR
   write_if_changed(args.out, emit_cpp(args.inventory.name, inv))
   if args.ids is not None:
      write_if_changed(args.ids, emit_ids(args.inventory.name, inv))
   return EXIT_OK


if __name__ == "__main__":
   sys.exit(main())
