#!/usr/bin/env python3
"""!D-36 §3.1 G0: a game's record layout without battle data.

   layout_compiler.py LAYOUT.json OUT.cpp [--platform P] [--storage BOXES SLOTS --ids IDS.h]

A project names a `capsule.record-layout/1` file as `"monster_layout"` in its `capsule.project/1` when its records
are read by its own code and it has no battle data (a game with battle data takes its layout from its structure
manifest, docs/BATTLE.md). The file holds:

- `schema`: "capsule.record-layout/1";
- `stats`: the stat names, in the order the per-stat roles hold them (their count is the layout's stat count);
- `monster_layout`: the v2 layout object (party size, move slots, roles; tools/battlec/layout.py), whose roles may
  give `"party": true` (the party part);
- `editor` (optional): notes for the studio.

The output defines capsule::monster::kLayout and its tables (layout.emit_layout_definition(), the same text the
battle compiler writes), checked against the platform's limits (record bytes, party size). It replaces the engine's
default, src/battle/layout_empty.cpp, at link.

D-36 §3.1 G4a: with --storage (a project's `"storage": {"boxes": B, "slots": S}`), the output also defines
capsule::storage::kStorage (B boxes of S slots, named "Box 1" ...; storage.emit_storage(), as the battle compiler's)
in place of src/storage/storage_empty.cpp, and --ids writes the storage's sizes (NUM_BOXES, BOX_SIZE, STORAGE_BYTES:
every slot's box part, STORAGE_USED_BYTES), for the game's capsule::storage::Buffer.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import text_encoder  # noqa: E402
from battlec.common import ManifestError, Texts, check_keys, register_keys  # noqa: E402
from battlec.layout import compile_layout, emit_layout_definition  # noqa: E402
from battlec.storage import compile_storage, emit_storage, storage_ids  # noqa: E402
from build_settings import SettingsError, platform_limits  # noqa: E402

## The file's schema.
SCHEMA = "capsule.record-layout/1"
## Exit status: written.
EXIT_OK = 0
## Exit status: the file is not a valid layout.
EXIT_ERROR = 1
## G4a: --storage's values (the project's "storage" "boxes" and "slots").
STORAGE_ARGS = ("BOXES", "SLOTS")

register_keys({"record_layout": {"schema", "editor", "stats", "monster_layout"}})


def compile_file(path: Path, platform: str | None = None) -> dict[str, Any]:
   """!Reads and compiles a record layout file.
   @param path      the capsule.record-layout/1 file
   @param platform  the platform whose limits apply (None: build_settings.DEFAULT_PLATFORM, the strictest)
   @return compile_layout()'s result
   @throws ManifestError when the file is not a valid layout
   """
   where = str(path)
   try:
      data = json.loads(path.read_text(encoding="utf-8"))
   except (OSError, json.JSONDecodeError) as e:
      raise ManifestError(f"{where}: {e}") from e
   check_keys(data, "record_layout", where)
   if data.get("schema") != SCHEMA:
      raise ManifestError(f"{where}: schema must be {SCHEMA}")
   stats = data.get("stats")
   if not isinstance(stats, list) or not stats or not all(isinstance(s, str) for s in stats):
      raise ManifestError(f"{where}: stats must list the stat names (the per-stat roles' elements)")
   limits = platform_limits(platform)
   if len(stats) > limits["max_stats"]:
      raise ManifestError(f"{where}: {len(stats)} stats, this platform's engine holds at most {limits['max_stats']}")
   return compile_layout(data.get("monster_layout"), f"{where}: monster_layout", limits["max_record_bytes"],
                         len(stats), limits["max_party_size"], battle=False)


def storage_of(lay: dict[str, Any], boxes: int, slots: int, platform: str | None = None) -> dict[str, Any]:
   """!G4a: a project's storage boxes over its layout (each slot one record's box part).
   @param lay       compile_file()'s result
   @param boxes     the project's "storage" "boxes"
   @param slots     its "slots" (per box)
   @param platform  the platform whose limits apply (None: the strictest)
   @return storage.compile_storage()'s result (the default names, "Box 1" ...)
   @throws ManifestError when the boxes do not fit the platform
   """
   return compile_storage({"box_count": boxes, "box_size": slots}, lay, platform_limits(platform),
                          "project.json", Texts(text_encoder.DEFAULT))


def emit_cpp(src_name: str, lay: dict[str, Any], storage: dict[str, Any] | None = None) -> str:
   """!The C++ source defining the build's layout (and, G4a, its storage's rules).
   @param src_name  the layout file's name (the header comment)
   @param lay       compile_file()'s result
   @param storage   storage_of()'s result, or None (the engine's default: no boxes)
   @return C++ source
   """
   L = [f"// Generated by tools/layout_compiler.py from {src_name}. Do not edit.",
        f"// Record {lay['bytes']} bytes: the box part {lay['box_bytes']}, the party part "
        f"{lay['bytes'] - lay['box_bytes']} ({', '.join(lay['party_roles']) or 'no party roles'}).",
        "#include \"capsule/monster/monster.h\""]
   if storage is not None:
      L.append("#include \"capsule/storage/storage.h\"")
   L += [""] + emit_layout_definition(lay)
   if storage is not None:
      L += emit_storage(storage)
   return "\n".join(L) + "\n"


def emit_ids(src_name: str, storage: dict[str, Any]) -> str:
   """!G4a: the storage's sizes for the game's code (capsule::storage::Buffer's).
   @param src_name  the layout file's name
   @param storage   storage_of()'s result
   @return C++ header
   """
   L = [f"// Generated by tools/layout_compiler.py from {src_name}. Do not edit.", "#pragma once", "",
        "#include <cstdint>", "", "namespace storage_ids", "{", ""]
   return "\n".join(L + storage_ids(storage) + ["} // namespace storage_ids", ""])


def write_if_changed(path: Path, text: str) -> None:
   """!Writes a file only when its text changes (so the game's sources do not rebuild for nothing).
   @param path  the file
   @param text  its text
   @return None
   """
   if not path.exists() or path.read_text(encoding="utf-8") != text:
      path.parent.mkdir(parents=True, exist_ok=True)
      path.write_text(text, encoding="utf-8")


def main(argv: Sequence[str] | None = None) -> int:
   """!The command line (see the module's comment).
   @param argv  arguments (default: sys.argv[1:])
   @return the exit status
   """
   p = argparse.ArgumentParser(description="a game's record layout without battle data (D-36 §3.1 G0)")
   p.add_argument("layout", type=Path, help="the capsule.record-layout/1 file")
   p.add_argument("out", type=Path, help="the C++ source to write")
   p.add_argument("--platform", default=None,
                  help="the platform whose limits apply (default: the GBA's, the strictest)")
   p.add_argument("--storage", type=int, nargs=len(STORAGE_ARGS), metavar=STORAGE_ARGS, default=None,
                  help="G4a: the project's storage boxes (boxes, slots per box)")
   p.add_argument("--ids", type=Path, default=None, help="G4a: the storage's sizes header to write (with --storage)")
   args = p.parse_args(argv)
   if (args.storage is None) != (args.ids is None):
      print("layout_compiler: --storage and --ids go together", file=sys.stderr)
      return EXIT_ERROR
   try:
      lay = compile_file(args.layout, args.platform)
      storage = storage_of(lay, *args.storage, args.platform) if args.storage is not None else None
   except (ManifestError, SettingsError, text_encoder.TextError) as e:
      print(f"layout_compiler: {e}", file=sys.stderr)
      return EXIT_ERROR
   write_if_changed(args.out, emit_cpp(args.layout.name, lay, storage))
   if storage is not None:
      write_if_changed(args.ids, emit_ids(args.layout.name, storage))
   return EXIT_OK


if __name__ == "__main__":
   sys.exit(main())
