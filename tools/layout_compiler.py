#!/usr/bin/env python3
"""!D-36 §3.1 G0: a game's record layout without battle data.

   layout_compiler.py LAYOUT.json OUT.cpp [--platform P]

A project names a `capsule.record-layout/1` file as `"monster_layout"` in its `capsule.project/1` when its records
are read by its own code and it has no battle data (a game with battle data takes its layout from its structure
manifest, docs/BATTLE.md). The file holds:

- `schema`: "capsule.record-layout/1";
- `stats`: the stat names, in the order the per-stat roles hold them (their count is the layout's stat count);
- `monster_layout`: the v2 layout object (party size, move slots, roles; tools/battlec/layout.py), whose roles may
  give `"party": true` (the party part);
- `editor` (optional): notes for the studio.

The output defines capsule::monster::kLayout and its tables (layout.emit_layout_definition(), the same text the
battle compiler writes), checked against the platform's limits (record bytes, party size). It replaces the engine's
default, src/battle/layout_empty.cpp, at link.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from battlec.common import ManifestError, check_keys, register_keys  # noqa: E402
from battlec.layout import compile_layout, emit_layout_definition  # noqa: E402
from build_settings import SettingsError, platform_limits  # noqa: E402

## The file's schema.
SCHEMA = "capsule.record-layout/1"
## Exit status: written.
EXIT_OK = 0
## Exit status: the file is not a valid layout.
EXIT_ERROR = 1

register_keys({"record_layout": {"schema", "editor", "stats", "monster_layout"}})


def compile_file(path: Path, platform: str | None = None) -> dict[str, Any]:
   """!Reads and compiles a record layout file.
   @param path      the capsule.record-layout/1 file
   @param platform  the platform whose limits apply (None: build_settings.DEFAULT_PLATFORM, the strictest)
   @return compile_layout()'s result
   @throws ManifestError when the file is not a valid layout
   """
   where = str(path)
   try:
      data = json.loads(path.read_text(encoding="utf-8"))
   except (OSError, json.JSONDecodeError) as e:
      raise ManifestError(f"{where}: {e}") from e
   check_keys(data, "record_layout", where)
   if data.get("schema") != SCHEMA:
      raise ManifestError(f"{where}: schema must be {SCHEMA}")
   stats = data.get("stats")
   if not isinstance(stats, list) or not stats or not all(isinstance(s, str) for s in stats):
      raise ManifestError(f"{where}: stats must list the stat names (the per-stat roles' elements)")
   limits = platform_limits(platform)
   if len(stats) > limits["max_stats"]:
      raise ManifestError(f"{where}: {len(stats)} stats, this platform's engine holds at most {limits['max_stats']}")
   return compile_layout(data.get("monster_layout"), f"{where}: monster_layout", limits["max_record_bytes"],
                         len(stats), limits["max_party_size"], battle=False)


def emit_cpp(src_name: str, lay: dict[str, Any]) -> str:
   """!The C++ source defining the build's layout.
   @param src_name  the layout file's name (the header comment)
   @param lay       compile_file()'s result
   @return C++ source
   """
   L = [f"// Generated by tools/layout_compiler.py from {src_name}. Do not edit.",
        f"// Record {lay['bytes']} bytes: the box part {lay['box_bytes']}, the party part "
        f"{lay['bytes'] - lay['box_bytes']} ({', '.join(lay['party_roles']) or 'no party roles'}).",
        "#include \"capsule/monster/monster.h\"", ""]
   return "\n".join(L + emit_layout_definition(lay)) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
   """!The command line (see the module's comment).
   @param argv  arguments (default: sys.argv[1:])
   @return the exit status
   """
   p = argparse.ArgumentParser(description="a game's record layout without battle data (D-36 §3.1 G0)")
   p.add_argument("layout", type=Path, help="the capsule.record-layout/1 file")
   p.add_argument("out", type=Path, help="the C++ source to write")
   p.add_argument("--platform", default=None,
                  help="the platform whose limits apply (default: the GBA's, the strictest)")
   args = p.parse_args(argv)
   try:
      lay = compile_file(args.layout, args.platform)
   except (ManifestError, SettingsError) as e:
      print(f"layout_compiler: {e}", file=sys.stderr)
      return EXIT_ERROR
   text = emit_cpp(args.layout.name, lay)
   # written only when it changes, so the game's sources do not rebuild for nothing
   if not args.out.exists() or args.out.read_text(encoding="utf-8") != text:
      args.out.parent.mkdir(parents=True, exist_ok=True)
      args.out.write_text(text, encoding="utf-8")
   return EXIT_OK


if __name__ == "__main__":
   sys.exit(main())
